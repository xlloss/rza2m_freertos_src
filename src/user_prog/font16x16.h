static inline const uint8_t *ssd1306_get_glyph16(char c, uint8_t *p_width)
{
    if (c >= '0' && c <= '9') {
        *p_width = width_num[c - '0'];
        return font16x16_num[c - '0'];
    }
    if (c >= 'A' && c <= 'Z') {
        *p_width = width_upper[c - 'A'];
        return font16x16_upper[c - 'A'];
    }
    if (c >= 'a' && c <= 'z') {
        *p_width = width_lower[c - 'a'];
        return font16x16_lower[c - 'a'];
    }
    if (c == ':') {
        *p_width = 4;
        return font16x16_colon;
    }
    if (c == '.') {
        *p_width = 4;
        return font16x16_dot;
    }
    if (c == '-') {
        *p_width = 6;
        return font16x16_minus;
    }
    if (c == '%') {
        *p_width = 10;
        return font16x16_percent;
    }
    if (c == '/') {
        *p_width = 6;
        return font16x16_slash;
    }
    if (c == '*' || (uint8_t)c == 0xB0) {
        *p_width = 5;
        return font16x16_degree;
    }
    if (c == ' ') {
        *p_width = 5;
        return NULL;
    }
    *p_width = 4;
    return NULL;
}

